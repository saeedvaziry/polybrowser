/// Position and size of a browser view inside its parent window.
///
/// Values are logical pixels (points), measured from the top-left corner of
/// the parent's content area. Backends convert to whatever the platform wants.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct Rect {
    pub x: f64,
    pub y: f64,
    pub width: f64,
    pub height: f64,
}

impl Rect {
    pub const fn new(x: f64, y: f64, width: f64, height: f64) -> Self {
        Self {
            x,
            y,
            width,
            height,
        }
    }
}
